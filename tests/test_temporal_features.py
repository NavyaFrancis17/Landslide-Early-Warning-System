"""
Tests for temporal features module and data leakage prevention (Phase 2).
"""

from pathlib import Path
import pandas as pd
import pytest
from landslide_early_warning.temporal_features import (
    extract_temporal_components,
    parse_event_dates,
    sort_chronologically,
)


def test_parse_event_dates_valid_and_invalid():
    df = pd.DataFrame({
        "event_date": ["2020-05-15", "08-01-2008 00:00", "invalid_date_string", None]
    })
    parsed, metrics = parse_event_dates(df, date_col="event_date")

    assert metrics["total_records"] == 4
    assert metrics["valid_date_count"] == 2
    assert metrics["missing_date_count"] == 1
    assert metrics["invalid_or_missing_count"] == 2
    assert parsed.iloc[0].year == 2020
    assert parsed.iloc[1].year == 2008
    assert pd.isna(parsed.iloc[2])
    assert pd.isna(parsed.iloc[3])


def test_extract_temporal_components():
    df = pd.DataFrame({
        "event_date": ["2026-07-15", "2026-01-10"]
    })
    parsed, _ = parse_event_dates(df, date_col="event_date")
    df_feat = extract_temporal_components(df, parsed)

    assert "event_year" in df_feat.columns
    assert "event_month" in df_feat.columns
    assert "event_day" in df_feat.columns
    assert "event_day_of_year" in df_feat.columns
    assert "season" in df_feat.columns

    assert df_feat["event_year"].iloc[0] == 2026
    assert df_feat["event_month"].iloc[0] == 7
    assert df_feat["season"].iloc[0] == "Summer"

    assert df_feat["event_month"].iloc[1] == 1
    assert df_feat["season"].iloc[1] == "Winter"


def test_sort_chronologically():
    df = pd.DataFrame({
        "event_datetime": pd.to_datetime(["2020-05-01", "2018-01-01", None, "2019-06-01"])
    })
    df_sorted = sort_chronologically(df, datetime_col="event_datetime")
    assert df_sorted["event_datetime"].iloc[0].year == 2018
    assert df_sorted["event_datetime"].iloc[1].year == 2019
    assert df_sorted["event_datetime"].iloc[2].year == 2020
    assert pd.isna(df_sorted["event_datetime"].iloc[3])


def test_processed_dataset_existence():
    """Verify that processed dataset CSV files were generated by process_data.py."""
    root_dir = Path(__file__).resolve().parent.parent
    clean_csv = root_dir / "data" / "processed" / "landslide_events_clean.csv"
    temporal_csv = root_dir / "data" / "processed" / "landslide_events_temporal.csv"

    assert clean_csv.exists(), "Clean processed CSV must exist"
    assert temporal_csv.exists(), "Temporal processed CSV must exist"

    df_clean = pd.read_csv(clean_csv, low_memory=False)
    df_temp = pd.read_csv(temporal_csv, low_memory=False)

    assert len(df_clean) == 11033
    assert len(df_temp) == 11033


def test_data_leakage_exclusion_rules():
    """
    Assert that post-event outcome fields are identified and excluded from predictive features.
    """
    leakage_sensitive_fields = [
        "landslide_size",
        "fatality_count",
        "injury_count",
        "submitted_date",
        "created_date",
        "last_edited_date",
    ]

    # Valid pre-event predictive candidate input list
    allowed_predictive_inputs = [
        "latitude",
        "longitude",
        "country_name",
        "admin_division_population",
        "event_year",
        "event_month",
        "event_day_of_year",
        "season",
    ]

    for field in leakage_sensitive_fields:
        assert field not in allowed_predictive_inputs, f"Leakage field '{field}' must not be in predictive inputs!"
